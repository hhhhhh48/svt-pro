# دالة لتوليد 20 سؤالاً لمادة معينة
def make_20_questions(subject_name, questions_list):
    # إذا كانت قائمة الأسئلة أقل من 20، نكررها مع تعديل بسيط (للتجربة)
    # في الواقع، يجب أن تضع 20 سؤالاً حقيقياً لكل مادة
    final_qs = []
    for i in range(20):
        if i < len(questions_list):
            final_qs.append(questions_list[i])
        else:
            final_qs.append({
                "q": f"سؤال تجريبي رقم {i+1} في مادة {subject_name} - (يجب استبداله بسؤال حقيقي)",
                "options": ["الخيار الأول", "الخيار الثاني", "الخيار الثالث", "الخيار الرابع"],
                "a": 0
            })
    return final_qs

