# دالة لحقن الأسئلة في المادة
def inject_exam(data, stream_slug, subject_slug, questions):
    for stream in data['streams']:
        if stream['slug'] == stream_slug:
            for subject in stream['subjects']:
                if subject['slug'] == subject_slug:
                    subject['bac_exam'] = make_20_questions(subject['name'], questions)
                    print(f"✅ تمت إضافة امتحان 20 سؤالاً لمادة {subject['name']} ({stream['name']})")
                    return

