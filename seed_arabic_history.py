def finalize(Q, subject_id):
    for q in Q:
        q["subjectId"] = subject_id
        q["type"] = "qcm"
        q["difficulty"] = 5
        q["status"] = "published"
        q["source"] = "bac_hard"
        q["question"] = q.pop("q")
        q["options"] = [{"id": chr(97+i), "text": opt} for i, opt in enumerate(q.pop("opts"))]
        q["correctOptionId"] = q.pop("a")
        q["explanation"] = q.pop("exp")
    return Q

